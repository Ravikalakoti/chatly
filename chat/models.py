from django.conf import settings
from django.db import models
from django.db.models import F, Q
import uuid


class Conversation(models.Model):
    """
    A one-to-one chat. The pair is stored in a fixed order (user_a.id < user_b.id)
    so there can only ever be one conversation per pair of people.
    """

    user_a = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="conversations_a")
    user_b = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="conversations_b")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["user_a", "user_b"], name="unique_conversation_pair"),
            models.CheckConstraint(condition=Q(user_a__lt=F("user_b")), name="conversation_users_ordered"),
        ]
        ordering = ["-updated_at"]

    def other_user(self, user):
        return self.user_b if user.pk == self.user_a_id else self.user_a

    def includes(self, user):
        return user.pk in (self.user_a_id, self.user_b_id)

    def __str__(self):
        return f"{self.user_a} ↔ {self.user_b}"

class ChatRequest(models.Model):
    """'I'd like to chat with you.' Becomes a Conversation once the receiver accepts."""

    PENDING, ACCEPTED, DECLINED = "pending", "accepted", "declined"
    STATUSES = [(PENDING, "Pending"), (ACCEPTED, "Accepted"), (DECLINED, "Declined")]

    sender = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="requests_sent")
    receiver = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="requests_received")
    status = models.CharField(max_length=10, choices=STATUSES, default=PENDING)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        constraints = [
            models.UniqueConstraint(fields=["sender", "receiver"], name="unique_chat_request_pair"),
            models.CheckConstraint(condition=~Q(sender=F("receiver")), name="chat_request_not_self"),
        ]

    def __str__(self):
        return f"{self.sender} → {self.receiver} ({self.status})"


def attachment_path(instance, filename):
    """Random file name, so a media URL can't be guessed."""
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else "bin"
    return f"chat/{uuid.uuid4().hex}.{ext}"

class Message(models.Model):
    TEXT, IMAGE, VOICE = "text", "image", "voice"
    KINDS = [(TEXT, "Text"), (IMAGE, "Image"), (VOICE, "Voice message")]

    conversation = models.ForeignKey(Conversation, on_delete=models.CASCADE, related_name="messages")
    sender = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="sent_messages")
    body = models.TextField(max_length=4000, blank=True, default="")  # empty for voice notes / photos without caption
    kind = models.CharField(max_length=8, choices=KINDS, default=TEXT)
    attachment = models.FileField(upload_to=attachment_path, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    read_at = models.DateTimeField(null=True, blank=True)
    # Random id generated by the sender's browser. Makes "resend after reconnect" idempotent.
    client_id = models.CharField(max_length=64, blank=True, default="")

    class Meta:
        ordering = ["id"]
        indexes = [models.Index(fields=["conversation", "id"])]
        constraints = [
            models.UniqueConstraint(
                fields=["sender", "client_id"],
                condition=~Q(client_id=""),
                name="unique_message_client_id_per_sender",
            )
        ]

    def __str__(self):
        return f"{self.sender}: {self.body[:30]}"
